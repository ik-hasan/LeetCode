class Solution {
public:
    long long countCommas(long long n) {
        if(n<=999) return 0;
        long long ans = 0;

        //1000 to 9999
        if(n<=9999){
            // for(int i=1000;i<=n;i++){
            //     ans+=1;
            // }
            ans += n-999;
            return ans;
        }
        else{
            // for(int i=1000;i<=9999;i++){
            //     ans+=1;
            // }
            ans += 9999-999;
        }

        //10000 to 99999
        if(n<=99999){
            // for(int i=10000;i<=n;i++){
            //     ans+=1;
            // }
            ans += n-9999;
            return ans;
        }
        else if(n>=99999){
            // for(int i=10000;i<=99999;i++){
            //     ans+=1;
            // }
            ans += 99999-9999;
        }
        
        //100000 to 999999
        if(n<=999999){
            // for(int i=100000;i<=n;i++){
            //     ans+=1;
            // }
            ans += n-99999;
            return ans;
        }
        else{
            // for(int i=100000;i<=999999;i++){
            //     ans+=1;
            // }
            ans += 999999-99999;
        }
        
        //1000000 to 9999999
        if(n<=9999999){
            // for(int i=1000000;i<=n;i++){
            //     ans+=2;
            // }
            ans += 2*(n-999999);
            return ans;
        }
        else{
            // for(int i=1000000;i<=9999999;i++){
            //     ans+=2;
            // }
            ans += 2*(9999999-999999);
        }
        
        //10000000 to 99999999
        if(n<=99999999){
            // for(long long i=10000000;i<=n;i++){
            //     ans+=2;
            // }
            ans += 2*(n-9999999);
            return ans;
        }
        else{
            // for(long long i=10000000;i<=99999999;i++){
            //     ans+=2;
            // }
            ans += 2*(99999999-9999999);
        }
        
        //100000000 to 999999999
        if(n<=999999999){
            // for(long long i=100000000;i<=n;i++){
            //     ans+=2;
            // }
            ans += 2*(n-99999999);
            return ans;
        }
        else{
            // for(long long i=100000000;i<=999999999;i++){
            //     ans+=2;
            // }
            ans += 2*(999999999-99999999);
        }

        //1000000000 t0 9999999999
        if(n<=9999999999){
            // for(long long i=1000000000;i<=n;i++){
            //     ans+=3;
            // }
            ans += 3*(n-999999999);
            return ans;
        }
        else{
            // for(long long i=1000000000;i<=9999999999;i++){
            //     ans+=3;
            // }
            ans += 3*(9999999999-999999999);
        }
        
        //10000000000 t0 99999999999
        if(n<=99999999999){
            // for(long long i=10000000000;i<=n;i++){
            //     ans+=3;
            // }
            ans += 3*(n-9999999999);
            return ans;
        }
        else{
            // for(long long i=10000000000;i<=99999999999;i++){
            //     ans+=3;
            // }
            ans += 3*(99999999999-9999999999);
        }
        
        //100000000000 t0 999999999999
        if(n<=999999999999){
            // for(long long i=100000000000;i<=n;i++){
            //     ans+=3;
            // }
            ans += 3*(n-99999999999);
            return ans;
        }
        else{
            // for(long long i=100000000000;i<=999999999999;i++){
            //     ans+=3;
            // }
            ans += 3*(999999999999-99999999999);
        }
        
        //1000000000000 t0 9999999999999
        if(n<=9999999999999){
            // for(long long i=1000000000000;i<=n;i++){
            //     ans+=4;
            // }
            ans += 4*(n-999999999999);
            return ans;
        }
        else{
            // for(long long i=1000000000000;i<=9999999999999;i++){
            //     ans+=4;
            // }
            ans += 4*(9999999999999-999999999999);
        }
        
        //10000000000000 t0 99999999999999
        if(n<=99999999999999){
            // for(long long i=10000000000000;i<=n;i++){
            //     ans+=4;
            // }
            ans += 4*(n-9999999999999);
            return ans;
        }
        else{
            // for(long long i=10000000000000;i<=99999999999999;i++){
            //     ans+=4;
            // }
            ans += 4*(99999999999999-9999999999999);
        }
        
        //100000000000000 t0 999999999999999
        if(n<=999999999999999){
            // for(long long i=100000000000000;i<=n;i++){
            //     ans+=4;
            // }
            ans += 4*(n-99999999999999);
            return ans;
        }
        else{
            // for(long long i=100000000000000;i<=999999999999999;i++){
            //     ans+=4;
            // }
            ans += 4*(999999999999999-99999999999999);
        }

        if(n==1000000000000000) ans+=5;
        
        return ans;
    }
};
